<script type="text/javascript">
    $(function () {
        var table = $('.table-datatable').DataTable({
            ajax: "{{ route('get-in-touch') }}",
            order: [
                [4, 'desc']
            ],
            columns: [{
                data: 'name',
                name: 'name',
